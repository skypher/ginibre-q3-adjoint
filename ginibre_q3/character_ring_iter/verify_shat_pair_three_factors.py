def hk(k):
    P = defaultdict(int)
    for a in range(k + 1):
        for i in range(-a, a + 1, 2):
            for j in range(-(k - a), k - a + 1, 2):
                P[(i, j)] += 1
    return P
def Sh(m):
    P = defaultdict(int)
    if m == 0:
        P[(0, 0)] = 2; return P
    for i in range(-m, m + 1, 2):
        P[(i, 0)] += 1; P[(0, i)] += 1
    return P
def mul(A, B):
    C = defaultdict(int)
    for (i, j), x in A.items():
        for (k, l), y in B.items():
            C[(i + k, j + l)] += x * y
    return C
